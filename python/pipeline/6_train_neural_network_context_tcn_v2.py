#!/usr/bin/env python3
"""
Train the contextual TCN v2 residual neural network.

The model keeps the v3 idea:

    residual = clean_delta - noisy_delta
    filtered_delta = noisy_delta + predicted_residual

but the input contains contextual features generated by:

    python/pipeline/5_generate_input_dataset_context_v1.py

Only the first three input columns are base deltas: dx, dy, dz.

This version splits the model into two additive branches:

    fast_residual = local short-context branch
    slow_residual = dilated TCN slow branch
    residual = fast_residual + slow_residual

The training model exposes total, fast, and slow residual channels so the loss
can penalize local residual error, accumulated trajectory error, and slow-branch
roughness. The saved inference model only outputs the final three residual
channels expected by GPX filters.
"""

