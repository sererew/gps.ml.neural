class ContextTrackDataset:
    """Dataset loader for contextual pre-split GPS track data."""

    def __init__(self, data_dir="data/input_context_v1"):
        self.data_dir = Path(data_dir)
        self.train_manifest_path = self.data_dir / "train" / "manifest_train.csv"
        self.val_manifest_path = self.data_dir / "val" / "manifest_val.csv"
        self.test_manifest_path = self.data_dir / "test" / "manifest_test.csv"
        self.norm_stats_path = self.data_dir / "norm_stats_train.json"

        required_files = [
            self.train_manifest_path,
            self.val_manifest_path,
            self.test_manifest_path,
            self.norm_stats_path,
        ]
        missing_files = [path for path in required_files if not path.exists()]
        if missing_files:
            raise FileNotFoundError(f"Missing files: {missing_files}")

        with open(self.norm_stats_path, "r", encoding="utf-8") as f:
            self.norm_stats = json.load(f)

        self.input_features = self.norm_stats.get("input_features")
        if not self.input_features:
            self.input_features = None
        self.label_features = self.norm_stats.get("label_features", DELTA_FEATURES)

        print(f"Context dataset loaded from {data_dir}")
        print(f"  - Stats: {self.norm_stats_path}")
        print(f"  - Input features: {self.input_features or 'from CSV columns'}")
        print(f"  - Label features: {self.label_features}")

    def _normalize_manifest_paths(self, manifest_df):
        """Normalize path separators for cross-platform compatibility."""
        for col in ["slice_path", "label_path", "mask_path"]:
            if col in manifest_df.columns:
                manifest_df[col] = manifest_df[col].fillna("").astype(str).apply(lambda p: p.replace("\\", "/"))

    def load_by_sets(self):
        """Load train, validation, and test splits."""
        train_manifest = pd.read_csv(self.train_manifest_path)
        val_manifest = pd.read_csv(self.val_manifest_path)
        test_manifest = pd.read_csv(self.test_manifest_path)

        self._normalize_manifest_paths(train_manifest)
        self._normalize_manifest_paths(val_manifest)
        self._normalize_manifest_paths(test_manifest)

        print("Loading contextual data by split:")
        print(f"  Train: {len(train_manifest)} windows")
        print(f"  Val: {len(val_manifest)} windows")
        print(f"  Test: {len(test_manifest)} windows")

        X_train, y_train, masks_train = self._load_data_batch(train_manifest)
        X_val, y_val, masks_val = self._load_data_batch(val_manifest)
        X_test, y_test, masks_test = self._load_data_batch(test_manifest)

        if len(X_train) == 0:
            raise ValueError("Could not load training data")
        if len(X_val) == 0:
            raise ValueError("Could not load validation data")
        if len(X_test) == 0:
            raise ValueError("Could not load test data")

        print(f"Data loaded - Train: {X_train.shape}, Val: {X_val.shape}, Test: {X_test.shape}")
        return (X_train, y_train, masks_train), (X_val, y_val, masks_val), (X_test, y_test, masks_test)

    def load_window_data(self, row):
        """Load one contextual window."""
        def _to_path(value):
            pstr = str(value).replace("\\", "/")
            return Path(pstr).expanduser()

        input_data = pd.read_csv(_to_path(row["slice_path"]))
        label_data = pd.read_csv(_to_path(row["label_path"]))
        mask_data = pd.read_csv(_to_path(row["mask_path"]))

        input_features = self.input_features
        if input_features is None:
            input_features = [col for col in input_data.columns if col != "time"]

        missing_input = [col for col in input_features if col not in input_data.columns]
        missing_label = [col for col in self.label_features if col not in label_data.columns]
        if missing_input:
            raise ValueError(f"Missing input columns {missing_input} in {row['slice_path']}")
        if missing_label:
            raise ValueError(f"Missing label columns {missing_label} in {row['label_path']}")

        X = input_data[input_features].to_numpy(dtype=np.float32)
        y = label_data[self.label_features].to_numpy(dtype=np.float32)
        mask = mask_data["mask"].to_numpy(dtype=np.float32)
        return X, y, mask

    def _load_data_batch(self, manifest_subset):
        """Load a complete split from a manifest."""
        X_list, y_list, masks_list = [], [], []
        for _, row in manifest_subset.iterrows():
            try:
                X, y, mask = self.load_window_data(row)
                X_list.append(X)
                y_list.append(y)
                masks_list.append(mask)
            except Exception as exc:
                print(f"Error loading window {row['slice_path']}: {exc}")

        return np.array(X_list), np.array(y_list), np.array(masks_list)


def split_training_output(y_pred):
    """Split training output into total, fast, and slow residual channels."""
    total_residual = y_pred[..., 0:3]
    fast_residual = y_pred[..., 3:6]
    slow_residual = y_pred[..., 6:9]
    return total_residual, fast_residual, slow_residual


def two_branch_residual_loss(y_true, y_pred):
    """Per-timestep loss for total residual, trajectory drift, and slow smoothness."""
    total_residual, _, slow_residual = split_training_output(y_pred)

    residual_mae = tf.reduce_mean(tf.abs(total_residual - y_true), axis=-1)

    trajectory_error = tf.cumsum(total_residual - y_true, axis=1)
    trajectory_mae = tf.reduce_mean(tf.abs(trajectory_error), axis=-1)

    slow_diff = slow_residual[:, 1:, :] - slow_residual[:, :-1, :]
    slow_smooth = tf.reduce_mean(tf.abs(slow_diff), axis=-1)
    slow_smooth = tf.pad(slow_smooth, [[0, 0], [1, 0]])

    return residual_mae + LAMBDA_TRAJ * trajectory_mae + LAMBDA_SLOW_SMOOTH * slow_smooth


def total_residual_mae_metric(y_true, y_pred):
    """Per-timestep MAE over the summed residual correction channels."""
    total_residual, _, _ = split_training_output(y_pred)
    return tf.reduce_mean(tf.abs(total_residual - y_true), axis=-1)


def trajectory_mae_metric(y_true, y_pred):
    """Per-timestep accumulated trajectory error metric in normalized units."""
    total_residual, _, _ = split_training_output(y_pred)
    trajectory_error = tf.cumsum(total_residual - y_true, axis=1)
    return tf.reduce_mean(tf.abs(trajectory_error), axis=-1)


def slow_smooth_metric(y_true, y_pred):
    """Per-timestep smoothness metric for the slow residual branch."""
    _, _, slow_residual = split_training_output(y_pred)
    slow_diff = slow_residual[:, 1:, :] - slow_residual[:, :-1, :]
    smooth = tf.reduce_mean(tf.abs(slow_diff), axis=-1)
    return tf.pad(smooth, [[0, 0], [1, 0]])


def tcn_block(x, filters, kernel_size, dilation_rate, dropout_rate):
    """Build one residual dilated temporal convolution block."""
    residual = x
    y = Conv1D(
        filters,
        kernel_size,
        padding="same",
        dilation_rate=dilation_rate,
        activation=None,
    )(x)
    y = LayerNormalization()(y)
    y = Activation("relu")(y)
    y = SpatialDropout1D(dropout_rate)(y)
    y = Conv1D(filters, 1, padding="same", activation=None)(y)
    y = LayerNormalization()(y)
    y = Add()([residual, y])
    return Activation("relu")(y)


def local_branch(inputs, output_features):
    """Create the short-context branch for fast local residual corrections."""
    x = Conv1D(64, 5, padding="same", activation=None, name="fast_conv1")(inputs)
    x = LayerNormalization(name="fast_norm1")(x)
    x = Activation("relu", name="fast_relu1")(x)
    x = Conv1D(64, 3, padding="same", activation=None, name="fast_conv2")(x)
    x = LayerNormalization(name="fast_norm2")(x)
    x = Activation("relu", name="fast_relu2")(x)
    x = Dense(32, activation="relu", name="fast_dense")(x)
    return Dense(output_features, activation="linear", name="fast_residual")(x)


def slow_branch(inputs, output_features):
    """Create the dilated TCN branch for slow residual corrections."""
    x = Conv1D(64, 1, padding="same", activation=None, name="slow_projection")(inputs)
    x = LayerNormalization(name="slow_projection_norm")(x)
    x = Activation("relu", name="slow_projection_relu")(x)

    for dilation_rate in [1, 2, 4, 8, 16, 32, 64, 128]:
        x = tcn_block(
            x,
            filters=64,
            kernel_size=5,
            dilation_rate=dilation_rate,
            dropout_rate=0.1,
        )

    x = Dense(64, activation="relu", name="slow_dense")(x)
    x = Dropout(0.2, name="slow_dropout")(x)
    return Dense(output_features, activation="linear", name="slow_residual")(x)


def create_models(sequence_length=3600, n_features=15, output_features=3):
    """Create training and inference models for the contextual TCN v2."""
    inputs = Input(shape=(sequence_length, n_features))
    fast_residual = local_branch(inputs, output_features)
    slow_residual = slow_branch(inputs, output_features)
    total_residual = Add(name="total_residual")([fast_residual, slow_residual])

    training_output = Concatenate(name="training_output")([total_residual, fast_residual, slow_residual])
    training_model = Model(inputs=inputs, outputs=training_output, name=f"{MODEL_TAG}_training")
    inference_model = Model(inputs=inputs, outputs=total_residual, name=MODEL_TAG)
    return training_model, inference_model


